/* Чтение деталей из файла в вектор */
void loadDetails(DetailVector *vec)
{
    FILE *file;          /* Указатель на файл */
    Detail temp;         /* Временная переменная для чтения */

    file = fopen(FILE_DETAILS, "r"); /* Открываем файл для чтения */
    if (file == NULL)                /* Если файл не существует */
    {
        printf("Файл деталей не найден. Будет создан при сохранении.\n"); /* Информируем */
        return;                      /* Выходим из функции */
    }

    /* Читаем детали из файла построчно */
    while (fscanf(file, "%d;%[^;];%[^;];%lf;%lf;%[^\n]\n",
                  &temp.code, temp.name, temp.material,
                  &temp.weight, &temp.price, temp.release_date) == 6)
    {
        pushDetail(vec, temp);       /* Добавляем прочитанную деталь в вектор */
    }
    fclose(file);                    /* Закрываем файл */
}

/* Запись всех деталей из вектора в файл */
void saveDetails(DetailVector *vec)
{
    FILE *file;          /* Указатель на файл */
    int i;               /* Переменная цикла */

    file = fopen(FILE_DETAILS, "w"); /* Открываем файл для записи */
    if (file == NULL)                /* Если не удалось открыть файл */
    {
        printf("Ошибка записи в файл деталей!\n"); /* Сообщение об ошибке */
        return;                      /* Выходим из функции */
    }

    for (i = 0; i < vec->size; i++)  /* Перебираем все детали */
    {
        /* Записываем каждую деталь в файл */
        fprintf(file, "%d;%s;%s;%.2f;%.2f;%s\n",
                vec->data[i].code,           /* Код детали */
                vec->data[i].name,           /* Название */
                vec->data[i].material,       /* Материал */
                vec->data[i].weight,         /* Вес */
                vec->data[i].price,          /* Цена */
                vec->data[i].release_date);  /* Дата выпуска */
    }
    fclose(file);                    /* Закрываем файл */
}

