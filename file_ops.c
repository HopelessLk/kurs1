/* Чтение учетных записей из файла в вектор */
void loadAccounts(AccountVector *vec)
{
    FILE *file;          /* Указатель на файл */
    Account temp;        /* Временная переменная для чтения */

    file = fopen(FILE_ACCOUNTS, "r"); /* Открываем файл для чтения */
    if (file == NULL)                 /* Если файл не существует */
    {
        /* Создаем файл с учетной записью администратора по умолчанию */
        file = fopen(FILE_ACCOUNTS, "w"); /* Открываем файл для записи */
        if (file == NULL)                 /* Если не удалось создать файл */
        {
            printf("Ошибка создания файла учетных записей!\n"); /* Сообщение об ошибке */
            return;                       /* Выходим из функции */
        }
        /* Записываем данные администратора по умолчанию */
        fprintf(file, "%s;%s;%d\n", DEFAULT_ADMIN_LOGIN, DEFAULT_ADMIN_PASSWORD, ROLE_ADMIN);
        fclose(file);                     /* Закрываем файл */

        /* Добавляем администратора в вектор */
        strcpy(temp.login, DEFAULT_ADMIN_LOGIN);       /* Копируем логин */
        strcpy(temp.password, DEFAULT_ADMIN_PASSWORD); /* Копируем пароль */
        temp.role = ROLE_ADMIN;                        /* Устанавливаем роль */
        pushAccount(vec, temp);                        /* Добавляем в вектор */
        printf("Создан файл учетных записей с администратором по умолчанию.\n"); /* Информируем */
        printf("Логин: %s, Пароль: %s\n", DEFAULT_ADMIN_LOGIN, DEFAULT_ADMIN_PASSWORD); /* Выводим данные */
        return;                           /* Выходим из функции */
    }

    /* Читаем учетные записи из файла построчно */
    while (fscanf(file, "%[^;];%[^;];%d\n", temp.login, temp.password, &temp.role) == 3)
    {
        pushAccount(vec, temp);           /* Добавляем прочитанную запись в вектор */
    }
    fclose(file);                         /* Закрываем файл */
}

/* Запись всех учетных записей из вектора в файл */
void saveAccounts(AccountVector *vec)
{
    FILE *file;          /* Указатель на файл */
    int i;               /* Переменная цикла */

    file = fopen(FILE_ACCOUNTS, "w"); /* Открываем файл для записи (перезапись) */
    if (file == NULL)                 /* Если не удалось открыть файл */
    {
        printf("Ошибка записи в файл учетных записей!\n"); /* Сообщение об ошибке */
        return;                       /* Выходим из функции */
    }

    for (i = 0; i < vec->size; i++)   /* Перебираем все учетные записи */
    {
        /* Записываем каждую учетную запись в файл */
        fprintf(file, "%s;%s;%d\n",
                vec->data[i].login,       /* Логин */
                vec->data[i].password,    /* Пароль */
                vec->data[i].role);       /* Роль */
    }
    fclose(file);                         /* Закрываем файл */
}

